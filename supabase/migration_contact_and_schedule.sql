-- ─────────────────────────────────────────────────────────────
-- 1. 연락처를 적을 자리를 만든다
--
-- 지망생이 자기소개에 인스타 아이디를 적는 건 적을 데가 없어서다. 그래서
-- 자기소개를 통째로 가렸었는데, 그러면 기획사가 심사할 재료까지 잃는다.
-- 칸을 만들어주면 거기 쓴다. 그리고 구조화된 필드라 게이트를 정확히 걸 수
-- 있다 — 본문에서 패턴을 찾아내는 것보다 확실하고, 노래 제목의 @를 잘못
-- 가릴 일도 없다.
--
-- phone은 이미 있는데 아무 데서도 안 쓰고 있어서 그대로 쓴다.
-- ─────────────────────────────────────────────────────────────
alter table profiles
  add column if not exists instagram text;


-- ─────────────────────────────────────────────────────────────
-- 2. 공고를 언제 열지는 Krookie가 정한다
--
-- 지금은 기획사가 아무 때나 올리면 즉시 공개된다. 제품의 정체가 "이번 주
-- 오디션 하나"인데 두 곳이 같은 주에 올리면 그 말이 성립하지 않고, 회차
-- 개념이 흐려지면 결과 확정과 7일 자동 처리도 같이 흐려진다.
--
-- 단순 승인제로는 부족하다 — 승인해도 언제 열릴지는 기획사가 정한 대로다.
-- 오픈 시각을 우리가 정해야 "다음 주는 A사, 그 다음 주는 B사"가 잡힌다.
-- 그리고 오픈 시각이 곧 알림 보내는 시각이라, "월 18시 오픈" 원칙이
-- 자동으로 지켜진다.
--
-- status에는 이미 'draft'가 쓰이고 있고 CHECK 제약이 없어서 값 추가는
-- 필요 없다. 슬롯 테이블도 필요 없다 — opens_at 하나면 순서가 정해진다.
-- ─────────────────────────────────────────────────────────────
alter table auditions
  add column if not exists opens_at timestamptz;

create index if not exists auditions_opens_at_idx
  on auditions (status, opens_at);

-- 이미 공개돼 있던 공고는 지금 열린 것으로 본다. 안 그러면 이 마이그레이션을
-- 돌리는 순간 살아 있던 공고가 전부 목록에서 사라진다.
update auditions
set opens_at = coalesce(opens_at, created_at)
where status in ('active', 'closed') and opens_at is null;
