-- 원클릭 기획사 초대 (2026-09-07)
--
-- 기획사에게 시키는 일을 0으로 만든다. 지금은 링크를 열면 이메일과
-- 비밀번호를 직접 입력해야 하는데, 그 비밀번호는 곧 잊힌다 — 한 달에
-- 한 번 들어오는 계정의 비밀번호를 기억하는 사람은 없다.
--
-- 초대를 만들 때 담당자 이메일을 같이 넣어두면, 기획사는 링크를 열고
-- 버튼 한 번만 누르면 된다. 비밀번호는 서버가 임의로 만들어 쥐고 있다가
-- 그 자리에서 로그인시키는 데만 쓰고 버린다. 나중에 필요해지면
-- /forgot-password로 본인이 정하면 된다.
--
-- 이메일이 비어 있는 초대는 기존 방식(직접 입력)으로 그대로 동작한다.
-- ─────────────────────────────────────────────────────────────

alter table agency_invites add column if not exists email text;

comment on column agency_invites.email is
  '담당자 이메일. 넣어두면 초대 링크가 원클릭으로 동작한다. 비우면 기획사가 직접 입력한다.';
