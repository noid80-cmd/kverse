        // 한 번만 NSClassFromString("PreferencesPlugin")으로 플러그인을 찾는다.
        // 이 시점에 SPM으로 별도 링크된 PreferencesPlugin 모듈이 dyld에 아직
        // 바인딩되지 않으면 등록에 실패해 "Preferences plugin is not implemented"
